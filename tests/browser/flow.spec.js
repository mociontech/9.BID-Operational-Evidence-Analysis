import { test, expect } from '@playwright/test';

test('two devices: playback, controls, end, reconnection and invalid pairing', async ({ browser }) => {
  const screenContext = await browser.newContext({ viewport: { width: 1280, height: 720 } });
  const tabletContext = await browser.newContext({ viewport: { width: 1024, height: 640 }, hasTouch: true });
  const screen = await screenContext.newPage(); const tablet = await tabletContext.newPage();
  const errors = []; screen.on('pageerror', error => errors.push(error.message)); tablet.on('pageerror', error => errors.push(error.message));
  await screen.goto('/pantalla');
  await expect(screen.locator('#arm')).toBeEnabled();
  await screen.locator('.remote-pairing summary').click();
  await screen.locator('#network').selectOption('http://127.0.0.1:5173');
  await expect(screen.locator('#pair-link')).toHaveAttribute('href', /token=/);
  const link = await screen.locator('#pair-link').getAttribute('href');
  await tablet.goto(link);
  await expect(tablet.locator('#tablet-status')).toHaveText('Activa la pantalla desde la computadora.');
  await screen.locator('#arm').click();
  await expect(screen.locator('#setup')).toBeHidden();
  await expect(tablet.locator('#tablet-home')).toBeEnabled();
  await screen.screenshot({ path: 'test-results/pantalla-inicio.png' });
  await tablet.screenshot({ path: 'test-results/tablet-inicio.png' });
  await tablet.locator('#tablet-home').click();
  await expect(tablet.locator('#controller')).toBeVisible();
  await expect(tablet.locator('.control-guidance')).toBeVisible();
  await expect(screen.locator('#video')).toHaveJSProperty('paused', true);
  await expect(screen.locator('#video')).toHaveJSProperty('currentTime', 1);
  await expect(tablet.locator('#play-pause')).toBeDisabled();
  const popup = await tablet.locator('.control-guidance').boundingBox();
  const viewport = await tablet.evaluate(() => ({ width: innerWidth, height: innerHeight }));
  expect(Math.abs(popup.x + popup.width / 2 - viewport.width / 2)).toBeLessThan(2);
  const timeline = await tablet.locator('.timeline').boundingBox();
  expect(popup.y + popup.height).toBeLessThan(timeline.y - 30);
  await screen.screenshot({ path: 'test-results/pantalla-frame-indicaciones.png' });
  await tablet.screenshot({ path: 'test-results/tablet-indicaciones.png' });
  await expect(tablet.locator('.control-guidance')).toBeHidden({ timeout: 8000 });
  await expect(screen.locator('#video')).toHaveJSProperty('paused', false);
  await expect(tablet.locator('#play-pause')).toBeEnabled();
  await tablet.locator('#play-pause').click();
  await expect(screen.locator('#video')).toHaveJSProperty('paused', true);
  await expect(tablet.locator('#play-pause')).toHaveAttribute('aria-label', 'Reproducir');
  await tablet.locator('#seek').fill('30'); await tablet.locator('#seek').dispatchEvent('change');
  await expect.poll(() => screen.locator('#video').evaluate(v => Math.round(v.currentTime))).toBe(30);
  await expect(tablet.locator('[data-value="-10"]')).toBeEnabled(); await tablet.locator('[data-value="-10"]').click();
  await expect.poll(() => screen.locator('#video').evaluate(v => Math.round(v.currentTime))).toBe(20);
  await expect(tablet.locator('[data-value="10"]')).toBeEnabled(); await tablet.locator('[data-value="10"]').click();
  await expect.poll(() => screen.locator('#video').evaluate(v => Math.round(v.currentTime))).toBe(30);
  await expect(tablet.locator('[data-action="reboot"]')).toBeEnabled(); await tablet.locator('[data-action="reboot"]').click();
  await expect(screen.locator('#video')).toHaveJSProperty('paused', false);
  await expect.poll(() => screen.locator('#video').evaluate(v => v.currentTime)).toBeLessThan(5);
  await expect(tablet.locator('[data-action="back"]')).toBeEnabled();
  await tablet.screenshot({ path: 'test-results/tablet-control.png' });
  await tablet.locator('[data-action="back"]').click();
  await expect(tablet.locator('#tablet-home')).toBeVisible(); await expect(screen.locator('#screen-home')).toBeVisible();
  await expect(tablet.locator('#tablet-home')).toBeEnabled(); await tablet.locator('#tablet-home').click();
  await expect(tablet.locator('#controller')).toBeVisible();
  await expect(tablet.locator('.control-guidance')).toBeHidden({ timeout: 8000 });
  await expect(screen.locator('#video')).toHaveJSProperty('paused', false);
  await screen.locator('#video').evaluate(v => { v.currentTime = v.duration - 0.2; });
  await expect(tablet.locator('#tablet-home')).toBeVisible(); await expect(screen.locator('#screen-home')).toBeVisible();
  await tabletContext.setOffline(true);
  await expect(tablet.locator('#tablet-home')).toBeDisabled({ timeout: 10000 });
  await tabletContext.setOffline(false);
  await expect(tablet.locator('#tablet-home')).toBeEnabled({ timeout: 15000 });
  await tablet.reload(); await expect(tablet.locator('#tablet-home')).toBeEnabled();
  const invalid = await tabletContext.newPage(); await invalid.goto('/tablet?room=invalid#token=invalid');
  await expect(invalid.locator('#notice')).toContainText('Vínculo no válido');
  expect(errors).toEqual([]);
  await screenContext.close(); await tabletContext.close();
});
